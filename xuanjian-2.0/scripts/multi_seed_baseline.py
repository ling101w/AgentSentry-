"""Multi-seed baseline report for the TemporalGAT detector.

For each seed in [42, 1337, 2025]:
  - load enriched dataset
  - stratified split (label)
  - train 60 epochs
  - evaluate on test set
  - break down per attack_type

Prints a table showing per-attack-type F1 across seeds so we can see
whether the model is genuinely learning (variance across seeds) or
just memorizing the schema (everything 1.0 across all seeds).
"""

from __future__ import annotations

import argparse
import json
import random
import sys
from pathlib import Path
from typing import Dict, List

import numpy as np
import torch
import torch.nn.functional as F
from torch.utils.data import DataLoader, Subset

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from models.temporal_gat.dataset import CausalGraphDataset, collate_graphs  # noqa: E402
from models.temporal_gat.model import TemporalGAT, compute_loss  # noqa: E402

# v2 generator emits "ipi_email_exfil" (the attack archetype key);
# enrichment keeps it as-is. The original synthetic_enriched folder
# was generated by a different script that wrote "IPI". Both spellings
# are mapped so the same report script works on either dataset.
ATTACK_FAMILIES = (
    "ipi_email_exfil", "IPI", "data_exfiltration", "privilege_escalation", "memory_poisoning",
)


def stratified_split(dataset, train_ratio, val_ratio, seed):
    labels = [s["meta"]["label"] for s in dataset.samples]
    by_label = {}
    for idx, label in enumerate(labels):
        by_label.setdefault(label, []).append(idx)
    rng = random.Random(seed)
    train_idx, val_idx, test_idx = [], [], []
    for label, indices in sorted(by_label.items()):
        rng.shuffle(indices)
        n = len(indices)
        n_train = int(n * train_ratio)
        n_val = int(n * val_ratio)
        train_idx.extend(indices[:n_train])
        val_idx.extend(indices[n_train:n_train + n_val])
        test_idx.extend(indices[n_train + n_val:])
    return sorted(train_idx), sorted(val_idx), sorted(test_idx)


def binary_metrics(y_true, y_prob, threshold=0.5):
    pred = (np.asarray(y_prob) >= threshold).astype(int)
    y_true = np.asarray(y_true).astype(int)
    tp = int(((pred == 1) & (y_true == 1)).sum())
    fp = int(((pred == 1) & (y_true == 0)).sum())
    fn = int(((pred == 0) & (y_true == 1)).sum())
    tn = int(((pred == 0) & (y_true == 0)).sum())
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    accuracy = (tp + tn) / max(len(y_true), 1)
    return {"accuracy": accuracy, "precision": precision,
            "recall": recall, "f1": f1,
            "tp": tp, "fp": fp, "fn": fn, "tn": tn}


@torch.no_grad()
def collect_test_predictions(model, loader, device):
    model.eval()
    probs, labels, attack_types = [], [], []
    for batch in loader:
        batch = {k: (v.to(device) if torch.is_tensor(v) else v) for k, v in batch.items()}
        outputs = model(batch)
        probs.extend(outputs["graph_prob"].cpu().numpy().tolist())
        labels.extend(batch["graph_label"].cpu().numpy().tolist())
        # meta is per-graph
        for meta in batch["meta"]:
            attack_types.append(meta.get("attack_type"))
    return np.array(probs), np.array(labels), attack_types


def per_attack_breakdown(probs, labels, attack_types):
    """Group test predictions by attack_type, compute F1 per group."""
    out: Dict[str, Dict] = {}
    for family in ATTACK_FAMILIES:
        mask = np.array([at == family for at in attack_types])
        if mask.sum() == 0:
            out[family] = {"count": 0, "f1": float("nan")}
            continue
        y = labels[mask]
        p = probs[mask]
        # In per-family evaluation, all positives are attack (label=1)
        # negatives are normal graphs - but normal graphs are typically
        # labelled "normal" with attack_type=None. We restrict to attacks
        # for family-specific metrics.
        if y.sum() == 0:
            out[family] = {"count": int(mask.sum()), "f1": float("nan")}
        else:
            m = binary_metrics(y, p)
            out[family] = {"count": int(mask.sum()), **m}
    # overall
    out["__overall__"] = binary_metrics(labels, probs)
    out["__overall__"]["count"] = int(len(labels))
    return out


def train_one_seed(args, data_dir: Path, seed: int, device: torch.device):
    torch.manual_seed(seed)
    np.random.seed(seed)
    random.seed(seed)

    graph_files = sorted(p for p in data_dir.glob("*.json")
                         if not p.name.endswith("_meta.json"))
    dataset = CausalGraphDataset(graph_files)
    train_idx, val_idx, test_idx = stratified_split(
        dataset, args.train_ratio, args.val_ratio, seed,
    )

    train_loader = DataLoader(Subset(dataset, train_idx), batch_size=args.batch_size,
                              shuffle=True, collate_fn=collate_graphs)
    val_loader = DataLoader(Subset(dataset, val_idx), batch_size=args.batch_size,
                            shuffle=False, collate_fn=collate_graphs)
    test_loader = DataLoader(Subset(dataset, test_idx), batch_size=args.batch_size,
                             shuffle=False, collate_fn=collate_graphs)

    model = TemporalGAT(
        feature_dim=dataset.feature_dim,
        hidden_dim=args.hidden_dim,
        num_layers=args.num_layers,
    ).to(device)
    optimizer = torch.optim.Adam(model.parameters(), lr=args.lr,
                                  weight_decay=args.weight_decay)
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=args.epochs)

    best_val_f1 = -1.0
    best_state = None
    for epoch in range(1, args.epochs + 1):
        model.train()
        for batch in train_loader:
            batch = {k: (v.to(device) if torch.is_tensor(v) else v) for k, v in batch.items()}
            optimizer.zero_grad()
            outputs = model(batch)
            loss = compute_loss(outputs, batch)
            loss.backward()
            optimizer.step()
        scheduler.step()

        # validation
        model.eval()
        vp, vl = [], []
        with torch.no_grad():
            for batch in val_loader:
                batch = {k: (v.to(device) if torch.is_tensor(v) else v) for k, v in batch.items()}
                outputs = model(batch)
                vp.extend(outputs["graph_prob"].cpu().numpy().tolist())
                vl.extend(batch["graph_label"].cpu().numpy().tolist())
        vp, vl = np.array(vp), np.array(vl)
        val_f1 = binary_metrics(vl, vp)["f1"]
        if val_f1 > best_val_f1:
            best_val_f1 = val_f1
            best_state = {k: v.detach().clone() for k, v in model.state_dict().items()}

    model.load_state_dict(best_state)
    probs, labels, attack_types = collect_test_predictions(model, test_loader, device)
    return per_attack_breakdown(probs, labels, attack_types)


def print_table(all_results: Dict[int, Dict[str, Dict]]):
    seeds = sorted(all_results.keys())
    families = list(ATTACK_FAMILIES) + ["__overall__"]

    print(f"\n{'='*78}")
    print(f"{'Family':<25} {'count':>5}  | {' '.join(f's={s:>4d}' for s in seeds)}  | {'mean':>6}  {'std':>5}")
    print(f"{'-'*78}")
    for family in families:
        fs = []
        cs = []
        for seed in seeds:
            r = all_results[seed][family]
            fs.append(r.get("f1", float("nan")))
            cs.append(r.get("count", 0))
        fs_arr = np.array([f for f in fs if not np.isnan(f)])
        if len(fs_arr) == 0:
            row_mean, row_std = float("nan"), float("nan")
        else:
            row_mean = float(fs_arr.mean())
            row_std = float(fs_arr.std())
        count = max(cs)
        f_strs = " ".join(f"{f:>5.3f}" if not np.isnan(f) else "  N/A" for f in fs)
        print(f"{family:<25} {count:>5}  | {f_strs}  | {row_mean:>6.3f}  {row_std:>5.3f}")
    print(f"{'='*78}\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", type=str,
                        default=str(PROJECT_ROOT / "data" / "synthetic_enriched"))
    parser.add_argument("--seeds", type=int, nargs="+", default=[42, 1337, 2025])
    parser.add_argument("--epochs", type=int, default=60)
    parser.add_argument("--batch-size", type=int, default=16)
    parser.add_argument("--hidden-dim", type=int, default=64)
    parser.add_argument("--num-layers", type=int, default=3)
    parser.add_argument("--lr", type=float, default=2e-3)
    parser.add_argument("--weight-decay", type=float, default=1e-4)
    parser.add_argument("--train-ratio", type=float, default=0.7)
    parser.add_argument("--val-ratio", type=float, default=0.15)
    args = parser.parse_args()

    data_dir = Path(args.data)
    if not data_dir.exists():
        raise SystemExit(f"data dir not found: {data_dir}")
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"[data] {data_dir} | device={device} | seeds={args.seeds} | epochs={args.epochs}")

    all_results: Dict[int, Dict[str, Dict]] = {}
    for seed in args.seeds:
        print(f"\n[seed={seed}] training...")
        all_results[seed] = train_one_seed(args, data_dir, seed, device)
        # Print running summary
        overall = all_results[seed]["__overall__"]
        print(f"  test F1={overall['f1']:.4f} P={overall['precision']:.4f} R={overall['recall']:.4f} "
              f"AUC-bin=(P+R)/2={ (overall['precision']+overall['recall'])/2:.4f}")

    print_table(all_results)

    # JSON dump
    out_path = PROJECT_ROOT / "checkpoints" / "multi_seed_baseline.json"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8") as fh:
        json.dump({str(k): v for k, v in all_results.items()}, fh, indent=2,
                  ensure_ascii=False, default=str)
    print(f"[saved] -> {out_path}")


if __name__ == "__main__":
    main()