"""Summary statistics for causal-graph JSONL produced by convert_openclaw.py.

Unlike scripts/dataset_stats.py (which targets a directory of normal_*.json /
attack_*.json files generated by the synthetic pipeline), this script reads
a JSONL where each line is a self-contained graph record. It re-uses the same
validation invariants (one intent node, edge weights in [0,1], known edge
types) and renders the same Markdown report.

Usage:
    python scripts/replay_stats.py \
        --graphs data/replay/replay_graphs.jsonl \
        --output data/replay/replay_stats.md
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path
from statistics import mean
from typing import Any, Dict, Iterable, List


KNOWN_EDGE_TYPES = {
    "intent_drives",
    "control_influence",
    "data_dependency",
    "call_sequence",
    "data_derivation",
}


def load_graphs(path: Path) -> List[Dict[str, Any]]:
    records: List[Dict[str, Any]] = []
    with path.open("r", encoding="utf-8") as fh:
        for lineno, line in enumerate(fh, 1):
            line = line.strip()
            if not line:
                continue
            try:
                record = json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(f"line {lineno}: invalid JSON ({exc})") from exc
            records.append(record)
    return records


def validate_and_annotate(records: Iterable[Dict[str, Any]]) -> List[Dict[str, Any]]:
    annotated: List[Dict[str, Any]] = []
    graph_ids: set[str] = set()
    for idx, record in enumerate(records):
        graph_id = record.get("graph_id")
        nodes = record.get("nodes")
        edges = record.get("edges")
        if not graph_id or not isinstance(nodes, list) or not isinstance(edges, list):
            raise ValueError(f"record {idx}: missing graph_id / nodes / edges")
        if graph_id in graph_ids:
            raise ValueError(f"duplicate graph_id: {graph_id}")
        graph_ids.add(graph_id)

        node_ids = [n.get("node_id") for n in nodes]
        if any(not nid for nid in node_ids) or len(node_ids) != len(set(node_ids)):
            raise ValueError(f"{graph_id}: node IDs must be present and unique")
        node_id_set = set(node_ids)

        control_edges = 0
        for edge in edges:
            if edge.get("source") not in node_id_set or edge.get("target") not in node_id_set:
                raise ValueError(f"{graph_id}: edge references unknown node")
            if edge.get("type") not in KNOWN_EDGE_TYPES:
                raise ValueError(f"{graph_id}: unknown edge type {edge.get('type')!r}")
            weight = edge.get("weight", 1.0)
            if not isinstance(weight, (int, float)) or not 0 <= weight <= 1:
                raise ValueError(f"{graph_id}: edge weight out of [0,1]")

        intents = [n for n in nodes if n.get("node_type") == "intent"]
        if len(intents) != 1:
            raise ValueError(f"{graph_id}: expected exactly one intent node")
        annotated.append(
            {
                **record,
                "_label": record.get("label", "unknown"),
                "_attack_type": record.get("attack_type"),
                "_task_type": intents[0].get("task_type", "unknown"),
                "_node_count": len(nodes),
                "_edge_count": len(edges),
                "_control_edge_count": control_edges,
            }
        )
    return annotated


def summarize(records: List[Dict[str, Any]]) -> Dict[str, Any]:
    labels = Counter(r["_label"] for r in records)
    tasks = Counter(r["_task_type"] for r in records)
    attack_types = Counter(
        r["_attack_type"] or "(none)" for r in records if r["_label"] == "attack"
    )
    sources = Counter(
        Path(r.get("source", "")).name or "(none)" for r in records
    )
    node_types = Counter(
        n["node_type"] for r in records for n in r.get("nodes", [])
    )
    edge_types = Counter(
        e["type"] for r in records for e in r.get("edges", [])
    )
    node_counts = [r["_node_count"] for r in records]
    edge_counts = [r["_edge_count"] for r in records]
    return {
        "total": len(records),
        "labels": labels,
        "tasks": tasks,
        "attack_types": attack_types,
        "sources": sources,
        "node_types": node_types,
        "edge_types": edge_types,
        "avg_nodes": mean(node_counts) if node_counts else 0,
        "avg_edges": mean(edge_counts) if edge_counts else 0,
    }


def render_markdown(summary: Dict[str, Any], graphs_path: Path) -> str:
    labels: Counter = summary["labels"]
    total = summary["total"] or 1

    def rows(counter: Counter, include_share: bool = True) -> str:
        lines = []
        for key, value in sorted(counter.items(), key=lambda kv: (-kv[1], kv[0])):
            if include_share:
                lines.append(f"| `{key}` | {value} | {value / total:.1%} |")
            else:
                lines.append(f"| `{key}` | {value} |")
        return "\n".join(lines) or ("| (none) | 0 | 0.0% |" if include_share else "| (none) | 0 |")

    attack_rows = "\n".join(
        f"| `{key}` | {value} |"
        for key, value in sorted(summary["attack_types"].items(), key=lambda kv: (-kv[1], kv[0]))
    ) or "| (none) | 0 |"

    return f"""# Replay Dataset Statistics

Source: `{graphs_path}`

## Overview

| Metric | Value |
|---|---:|
| Total records | {summary['total']} |
| Normal | {labels.get('normal', 0)} |
| Attack | {labels.get('attack', 0)} |
| Unknown / unlabeled | {labels.get('unknown', 0)} |
| Average nodes per graph | {summary['avg_nodes']:.2f} |
| Average edges per graph | {summary['avg_edges']:.2f} |

## Labels

| Label | Count | Share |
|---|---:|---:|
{rows(labels)}

## Task Types (intent node)

| Task type | Count |
|---|---:|
{rows(summary['tasks'], include_share=False)}

## Attack Types

| Attack type | Count |
|---|---:|
{attack_rows}

## Graph Schema Usage

### Nodes

| Node type | Count |
|---|---:|
{rows(summary['node_types'], include_share=False)}

### Edges

| Edge type | Count |
|---|---:|
{rows(summary['edge_types'], include_share=False)}
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--graphs", required=True, help="replay graphs jsonl path")
    parser.add_argument(
        "--output",
        default=None,
        help="markdown output path (default: <graphs>.stats.md)",
    )
    args = parser.parse_args()

    graphs_path = Path(args.graphs).resolve()
    if not graphs_path.is_file():
        raise SystemExit(f"graphs file not found: {graphs_path}")

    raw = load_graphs(graphs_path)
    records = validate_and_annotate(raw)
    summary = summarize(records)

    output = Path(args.output) if args.output else graphs_path.with_suffix(".stats.md")
    output.write_text(render_markdown(summary, graphs_path), encoding="utf-8")

    print(f"[replay_stats] total={summary['total']}")
    print(f"  normal   = {summary['labels'].get('normal', 0)}")
    print(f"  attack   = {summary['labels'].get('attack', 0)}")
    print(f"  unknown  = {summary['labels'].get('unknown', 0)}")
    print(f"  nodes/avg= {summary['avg_nodes']:.2f}   edges/avg= {summary['avg_edges']:.2f}")
    print(f"  wrote {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
